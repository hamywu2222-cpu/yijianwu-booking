/** 無自備車行程排前；2D1N 再先於 3D2N */
export function splitByVehicle<T extends { id: string; noVehicle?: boolean }>(
  items: readonly T[],
): { noVehicle: T[]; withVehicle: T[] } {
  const stayRank = (id: string) =>
    id.startsWith('2d1n') ? 0 : id.startsWith('3d2n') ? 1 : 2;
  const noVehicle = items.filter((i) => i.noVehicle).sort((a, b) => stayRank(a.id) - stayRank(b.id));
  const withVehicle = items.filter((i) => !i.noVehicle);
  return { noVehicle, withVehicle };
}

