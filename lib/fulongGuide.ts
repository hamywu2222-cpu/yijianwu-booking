/** 從一間屋出發的交通時間（單程） */
export type FromOneHouse = {
  km?: string;
  /** 排序用中位數公里 */
  kmSort: number;
  walk?: string;
  bike: string;
  scooter: string;
  car: string;
  note?: string;
};

export type FulongSpot = {
  id: string;
  name: string;
  tagline: string;
  category: 'water' | 'snorkel' | 'bike' | 'hike' | 'culture' | 'food';
  distance: string;
  travel: string;
  fromBase: FromOneHouse;
  image?: string;
  body: string;
  activities: string[];
  tips: string[];
  mapsUrl?: string;
  bookingUrl?: string;
  bookingLabel?: string;
};

export function sortSpotsByDistance<T extends { fromBase: FromOneHouse }>(spots: T[]): T[] {
  return [...spots].sort((a, b) => a.fromBase.kmSort - b.fromBase.kmSort);
}

